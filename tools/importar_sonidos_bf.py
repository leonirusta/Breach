def main():
    dst = os.path.abspath(DST)
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    usados = set()
    n = 0
    total = 0
    vacias = []
    for clave, (carpeta, pats) in MAPA.items():
        origen = os.path.join(SRC, carpeta)
        archivos = sorted(os.listdir(origen))
        elegidos = []
        for f in archivos:
            nombre = re.sub(r"^\d+_", "", f)
            if nombre.endswith("_SILENT.ogg"):
                continue
            if any(re.search(p, nombre) for p in pats):
                elegidos.append(f)
        if not elegidos:
            vacias.append(clave)
            continue
        sub, pref = clave.rsplit("/", 1)
        os.makedirs(os.path.join(dst, sub), exist_ok=True)
        for i, f in enumerate(elegidos, 1):
            s = os.path.join(origen, f)
            shutil.copyfile(s, os.path.join(dst, sub, "%s%d.ogg" % (pref, i)))
            usados.add(os.path.join(carpeta, f))
            total += os.path.getsize(s)
            n += 1
    print("copiados %d archivos (%d distintos), %.1f MB, %d claves" % (n, len(usados), total / 1048576, len(MAPA)))
    if vacias:
        print("CLAVES SIN ARCHIVO:", vacias)
    todos = sum(len(fs) for _, _, fs in os.walk(SRC))
    print("sin usar: %d de %d (sobre todo menus de BF que Breach no tiene)" % (todos - len(usados), todos))


if __name__ == "__main__":
    main()
