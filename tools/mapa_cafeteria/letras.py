def pixeles(texto, fuente="peque", separacion=1):
    """[(col, fila)] con fila 0 arriba, y el ancho en puntos."""
    tabla = GRANDE if fuente == "grande" else PEQUE
    out, x = [], 0
    for ch in texto.upper():
        g = tabla.get(ch) or tabla.get(" ") or PEQUE[" "]
        if ch == " " and fuente == "grande":
            x += 4
            continue
        for fila, linea in enumerate(g):
            for col, c in enumerate(linea):
                if c == "#":
                    out.append((x + col, fila))
        if ch == "É" and fuente == "grande":
            out += [(x + c, f) for c, f in TILDE_GRANDE]
        elif ch == "É":
            out += [(x + 2, -2), (x + 3, -2)]
        x += len(g[0]) + separacion
    return out, max(0, x - separacion)


def contorno(pix):
    """Los puntos de alrededor (8 vecinos) que no son de la letra: el perfilado de un grafiti."""
    s = set(pix)
    out = set()
    for c, f in pix:
        for dc in (-1, 0, 1):
            for df in (-1, 0, 1):
                q = (c + dc, f + df)
                if q not in s:
                    out.add(q)
    return sorted(out)


